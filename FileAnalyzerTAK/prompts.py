def create_analysis_prompt(query: str) -> str:
    """Создает промпт для анализа запроса"""
    return f"""Проанализируй следующий запрос и определи, какую информацию нужно искать в документах:
    {query}
    
    Укажи:
    1. Тип запроса (общий/конкретный)
    2. Ключевые слова и фразы для поиска
    3. Возможные разделы, где может находиться информация
    4. Как лучше структурировать ответ"""

def create_rag_prompt(query: str, context: str) -> str:
    """Создает промпт для RAG с учетом контекста"""
    return f"""Ты - ассистент для поиска информации в документах. Твоя задача - найти и проанализировать информацию из документов, соответствующую запросу.

Запрос пользователя: {query}

Доступные документы:
{context}

Инструкции:
1. Внимательно проанализируй все предложения из документов
2. Найди информацию, которая соответствует запросу
3. Если информация найдена, укажи:
   - Точную страницу и раздел, где найдена информация
   - Основную информацию из документа
4. Если информация не найдена, ответь "Информация не найдена"

Формат ответа:
"Информация найдена на странице <номер страницы> в разделе <Наименование раздела>: <Ответ с найденной информацией>"

ВАЖНО: 
- Отвечай на основе информации из документов
- Можешь перефразировать и интерпретировать информацию для лучшего понимания
- Не добавляй информацию из своих знаний
- Если информация не найдена, так и скажи
- Не меняй тему разговора
- Не используй фразы типа "Не люблю менять тему разговора" или подобные
- Не используй никаких вводных фраз, начинай сразу с ответа
- Если информация найдена в нескольких местах, укажи все источники"""

def create_general_content_prompt(query: str, context: str) -> str:
    """Создает промпт для анализа общего содержания документов"""
    return f"""Ты - ассистент для анализа документов. Твоя задача - предоставить общее описание содержания документов.

Запрос пользователя: {query}

Доступные документы:
{context}

Инструкции:
1. Проанализируй все документы и их разделы
2. Составь структурированное описание содержания
3. Укажи:
   - Основные темы и разделы каждого документа
   - Ключевые моменты и важную информацию
   - Связи между разделами и документами
4. Предоставь информацию в удобном для восприятия виде

Формат ответа:
"Общее содержание документов:

1. <Название первого документа>:
   - Основные темы: <список тем>
   - Ключевые моменты: <список важных моментов>
   - Структура: <описание структуры документа>

2. <Название второго документа>:
   - Основные темы: <список тем>
   - Ключевые моменты: <список важных моментов>
   - Структура: <описание структуры документа>

Связи между документами:
<описание связей и общих тем>"

ВАЖНО: 
- Используй информацию только из предоставленных документов
- Структурируй ответ для удобного восприятия
- Выделяй основные темы и важные моменты
- Показывай связи между документами
- Не добавляй информацию из своих знаний"""

def create_final_prompt(query: str, response: str) -> str:
    """Создает промпт для улучшения ответа"""
    return f"""Улучши следующий ответ, сделав его более понятным и структурированным:
    Запрос: {query}
    Найденная информация: {response}
    
    Сделай ответ более четким и информативным, обязательно сохранив указания на страницы и разделы документов.
    Убедись, что информация из всех релевантных файлов включена в ответ.
    Если это общий запрос о содержании, структурируй ответ в виде списка основных тем и разделов."""